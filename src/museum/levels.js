// Difficulty: gentle start, steep after 20, brutal at 40.
export function difficulty(i) {
  const x = i / (LEVELS.length - 1);
  return {
    count: Math.round(5 + i * 0.45 + x * x * 14),
    hp: 1 + x * 2.4 + x ** 3 * 4,
    speed: 0.85 + x * 0.85,
    dmg: 5 + x * 9 + x ** 2.5 * 8,
    rate: 1 + x * 1.1,
    boss: (i + 1) % 5 === 0,
  };
}
